/**
 * Local development bootstrap.
 *
 * Deploys the test-only MockAgentId together with the real AgentIdRegistry on a
 * running Hardhat node, seeds a few Agent IDs, exercises the register / check-in
 * / premium-slot paths, and writes web/.env.local so the Vite app can read the
 * deployment. Never used against a public network.
 *
 *   npx hardhat node                       # terminal 1
 *   npx hardhat run scripts/dev-local.ts   # terminal 2
 */
import { ethers, network } from "hardhat";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

async function main() {
  if (network.name !== "hardhat" && network.name !== "localhost") {
    throw new Error(`Refusing to seed a non-local network: ${network.name}`);
  }

  const signers = await ethers.getSigners();
  const [deployer, alice, bob, carol] = signers;

  const Mock = await ethers.getContractFactory("MockAgentId");
  const mock = await Mock.deploy();
  await mock.waitForDeployment();
  const mockAddress = await mock.getAddress();

  const Registry = await ethers.getContractFactory("AgentIdRegistry");
  const registry = await Registry.deploy(mockAddress);
  await registry.waitForDeployment();
  const registryAddress = await registry.getAddress();

  // Agent IDs for the seeded wallets.
  const holders = [deployer, alice, bob, carol];
  for (let i = 0; i < holders.length; i += 1) {
    const tx = await mock.mint(await holders[i].getAddress(), i + 1);
    await tx.wait();
  }

  // Passport + first check-in for three wallets.
  for (let i = 0; i < 3; i += 1) {
    const holder = holders[i];
    const agent = holder.address;
    const reg = await registry.connect(holder).register(i + 1);
    await reg.wait();
    const check = await registry.connect(holder).checkIn();
    await check.wait();
  }

  // One wallet buys a premium slot (real BNB payment through the contract).
  const price = await registry.slotPrice();
  const buy = await registry.connect(holders[1]).purchaseSlot({ value: price });
  await buy.wait();

  // A second check-in for the first wallet, after jumping the cooldown.
  await ethers.provider.send("evm_increaseTime", [5 * 60 * 60]);
  await ethers.provider.send("evm_mine", []);
  const second = await registry.connect(holders[0]).checkIn();
  await second.wait();

  const stats = await registry.stats();
  const leaderboard = await registry.leaderboard();

  const deploymentsDir = join(__dirname, "..", "deployments");
  mkdirSync(deploymentsDir, { recursive: true });
  writeFileSync(
    join(deploymentsDir, "localhost.json"),
    JSON.stringify(
      {
        network: "localhost",
        chainId: 31337,
        registry: registryAddress,
        points: await registry.points(),
        receipts: await registry.receipts(),
        agentId: mockAddress,
        agentIdKind: "MockAgentId (test only)",
        owner: await registry.owner(),
        deployedAt: new Date().toISOString(),
      },
      null,
      2
    ) + "\n"
  );

  const envLocal = [
    "# Generated by scripts/dev-local.ts — local Hardhat only.",
    `VITE_REGISTRY_LOCAL=${registryAddress}`,
    `VITE_AGENT_ID_LOCAL=${mockAddress}`,
    "",
  ].join("\n");
  writeFileSync(join(__dirname, "..", "web", ".env.local"), envLocal);

  console.log("Local AgentPass deployment");
  console.log("  MockAgentId  :", mockAddress);
  console.log("  Registry     :", registryAddress);
  console.log("  Points       :", await registry.points());
  console.log("  Receipts     :", await registry.receipts());
  console.log("  Agents       :", stats[0].toString());
  console.log("  Check-ins    :", stats[1].toString());
  console.log("  Volume (BNB) :", ethers.formatEther(stats[2]));
  console.log("  Receipts     :", stats[3].toString());
  console.log("  Leaderboard  :", leaderboard[0].length, "entries");
  console.log("  web/.env.local written — restart Vite to pick it up.");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
